    /// <summary>
    /// Progression rungs, in order. The numeric value is the ordering used for ceiling
    /// checks: a portal carries its own tier and everything below it.
    /// </summary>
    internal enum BiomeTier
    {
        None = 0,
        BlackForest = 1,
        Swamp = 2,
        Mountain = 3,
        Plains = 4,
        Mistlands = 5,
        Ashlands = 6,
    }

    /// <summary>
    /// Everything that varies per rung, in one place. Prefab and item names below were
    /// taken from the item report generated by a real game start, not from recall.
    /// </summary>
    internal sealed class TierInfo
    {
        internal BiomeTier Tier;

        /// <summary>Prefab name of the portal piece this mod creates for the tier.</summary>
        internal string PortalPrefab;

        /// <summary>Localization token for the piece name.</summary>
        internal string NameToken;

        internal string DisplayName;
        internal string Description;

        /// <summary>The boss whose spirit collects the toll, for message copy.</summary>
        internal string SpiritName;

        /// <summary>
        /// Global key set when the boss dies. Checked with the string overload of
        /// ZoneSystem.GetGlobalKey, because Queen and Fader have no GlobalKeys enum member.
        /// </summary>
        internal string BossKey;

        /// <summary>Base hue. Scaled up for the connected glow, down for the idle tint.</summary>
        internal Color Hue;

        internal string DefaultTollItem;
        internal int DefaultTollAmount;

        /// <summary>Per-unit chance to lose this tier's metal while its boss lives.</summary>
        internal float DefaultLossRate;

        internal string CraftingStation;

        /// <summary>Build cost as (prefab, amount) pairs.</summary>
        internal (string Item, int Amount)[] Recipe;

        /// <summary>Cargo this rung admits that lower rungs do not.</summary>
        internal string[] Cargo;

        /// <summary>
        /// The subset of <see cref="Cargo"/> that can be destroyed in transit. Ores and
        /// bars only: quest and mechanism items are gated by tier but never taken, because
        /// they are irreplaceable.
        /// </summary>
        internal string[] LossEligible;
    }


        private static readonly Dictionary<BiomeTier, TierInfo> ByTier =
            All.ToDictionary(t => t.Tier);

        private static readonly Dictionary<string, TierInfo> ByPortalPrefab =
            All.ToDictionary(t => t.PortalPrefab, System.StringComparer.OrdinalIgnoreCase);

        internal static TierInfo Get(BiomeTier tier) =>
            ByTier.TryGetValue(tier, out var info) ? info : null;

        /// <summary>
        /// The tier a portal prefab grants, or None for wood, stone and anything else this
        /// mod did not create. Callers use None to mean "leave vanilla alone".
        /// </summary>
        internal static BiomeTier TierOfPortal(string prefabName)
        {
            if (string.IsNullOrEmpty(prefabName))
            {
                return BiomeTier.None;
            }

            // Instantiated objects carry the "(Clone)" suffix.
            var clean = prefabName.EndsWith("(Clone)")
                ? prefabName.Substring(0, prefabName.Length - 7)
                : prefabName;

            return ByPortalPrefab.TryGetValue(clean, out var info) ? info.Tier : BiomeTier.None;
        }

        internal static bool IsTollboundPortal(string prefabName) =>
            TierOfPortal(prefabName) != BiomeTier.None;
    }
